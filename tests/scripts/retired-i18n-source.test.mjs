import assert from "node:assert/strict";
import { readFile, access } from "node:fs/promises";
import test from "node:test";
const root = new URL("../../", import.meta.url);

test("retired converter and archive-rewriting entry points cannot be run", async () => {
  for (const path of ["scripts/convert-lingui.mjs", "scripts/reconcile-plugin-audit.mjs", "scripts/lib/legacy-catalogue-import.mjs", "scripts/lib/lingui-retired.mjs"])
    await assert.rejects(access(new URL(path, root)), { code: "ENOENT" });
});
test("active tooling and source no longer advertise legacy resource machinery", async () => {
  const read = path => readFile(new URL(path, root), "utf8");
  assert.doesNotMatch(await read("eslint.config.mjs"), /resources\/en\.ts|englishLocaleSentenceCaseOptions/);
  assert.doesNotMatch(await read("src/i18n/messages.ts"), /Generated by scripts\/convert-lingui/);
  assert.doesNotMatch(await read("src/i18n/index.ts"), /TranslationKey/);
  assert.doesNotMatch(await read("docs/development/i18n-state-manager.md"), /remain trusted migration inputs|scripts\/convert-lingui/);
});
test("retired grouping implementations are absent; the live filter grouping adapter remains", async () => {
  for (const path of ["src/utils/GroupingUtils.ts", "src/services/HierarchicalGroupingService.ts"])
    await assert.rejects(access(new URL(path, root)), { code: "ENOENT" });
  assert.doesNotMatch(await readFile(new URL("src/services/FilterService.ts", root), "utf8"), /getHierarchicalGroupedTasks/);
  assert.doesNotMatch(await readFile(new URL("src/bases/helpers.ts", root), "utf8"), /renderGroupedTasksInBasesView/);
  assert.doesNotMatch(await readFile(new URL("src/services/filter-service/userFieldValues.ts", root), "utf8"), /getHierarchicalUserFieldGroupValues/);
  assert.match(await readFile(new URL("src/services/filter-service/filterTaskGrouping.ts", root), "utf8"), /export function groupFilterTasks/);
});
