import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const text = readFileSync(new URL('vendor/mdbase-contracts/tasknotes.task-0.3.0-rc.21.json', root), 'utf8');
const digest = createHash('sha256').update(text).digest('hex');
if (digest !== '35a439cd50aeca1ddb1ec2a260822133881e26d901f0851190adcddb56aca5be') throw new Error('TaskNotes canonical pack integrity mismatch');
const pack = JSON.parse(text);
if (pack.manifest.id !== 'tasknotes.task' || pack.manifest.version !== '0.3.0-rc.21') throw new Error('Wrong TaskNotes pack');
// The pinned upstream seed uses a historical wildcard. Correct the embedded
// copy while keeping the original provision and its digests intact.
const seed = pack.resources.find(({ source }) => source === 'types/tasknotes-task/6.md');
const legacyLinkRules = /^(    (?:projects\[\]|occurrence_template):\n)      target_type: any\n(?=      validate_exists: false$)/gm;
if ([...seed.document.matchAll(legacyLinkRules)].length !== 2) throw new Error('Unexpected TaskNotes seed link rules');
seed.document = seed.document.replace(legacyLinkRules, '$1');
const output = '// Generated by scripts/verify-tasknotes-pack.mjs; do not edit.\nexport const canonicalTaskNotesResources = ' + JSON.stringify(pack.resources, null, '\t') + ';\n';
const destination = fileURLToPath(new URL('src/services/canonicalTaskNotesPack.ts', root));
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Stale embedded TaskNotes pack');
} else writeFileSync(destination, output);
