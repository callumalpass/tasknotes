import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const text = readFileSync(new URL('vendor/mdbase-contracts/tasknotes.task-0.3.0-rc.17.json', root), 'utf8');
const digest = createHash('sha256').update(text).digest('hex');
if (digest !== 'aa03bd096f62868b4b414e753cd01024d33d8cd193c902f3cb0f3526c3149e8e') throw new Error('TaskNotes canonical pack integrity mismatch');
const pack = JSON.parse(text);
if (pack.manifest.id !== 'tasknotes.task' || pack.manifest.version !== '0.3.0-rc.17') throw new Error('Wrong TaskNotes pack');
const output = '// Generated by scripts/verify-tasknotes-pack.mjs; do not edit.\nexport const canonicalTaskNotesResources = ' + JSON.stringify(pack.resources, null, '\t') + ';\n';
const destination = fileURLToPath(new URL('src/services/canonicalTaskNotesPack.ts', root));
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Stale embedded TaskNotes pack');
} else writeFileSync(destination, output);
