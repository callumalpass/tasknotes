import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
const root = new URL('../', import.meta.url);
const text = readFileSync(new URL('vendor/mdbase-contracts/tasknotes.task-0.3.0-rc.23.json', root), 'utf8');
const digest = createHash('sha256').update(text).digest('hex');
if (digest !== 'cd46a5e3fdbff1bac5ad73dba7404fc9a9254e169851242f97b21612ffe3b6ed') throw new Error('TaskNotes canonical pack integrity mismatch');
const pack = JSON.parse(text);
if (pack.manifest.id !== 'tasknotes.task' || pack.manifest.version !== '0.3.0-rc.23') throw new Error('Wrong TaskNotes pack');
// The pinned upstream seed uses a historical wildcard. Correct the embedded
// copy while keeping the original provision and its digests intact.
const seed = pack.resources.find(({ source }) => source === 'types/tasknotes-task/8.md');
const legacyLinkRules = /^(    (?:projects\[\]|occurrence_template):\n)      target_type: any\n(?=      validate_exists: false$)/gm;
if ([...seed.document.matchAll(legacyLinkRules)].length !== 2) throw new Error('Unexpected TaskNotes seed link rules');
seed.document = seed.document.replace(legacyLinkRules, '$1');
const seedType = YAML.parse(seed.document.split('\n---\n', 1)[0]);
const contractVersion = seedType.implements.find(({ contract }) => contract === 'tasknotes.task')?.version;
if (contractVersion !== '0.3.0-rc.7' || seedType.version !== 6) throw new Error('Unexpected TaskNotes type version');
const { due, scheduled, dateCreated, dateModified } = seedType.schema.value.properties;
const fields = { due, scheduled, dateCreated, dateModified };
const recordSchema = JSON.parse(pack.resources.find(({ source }) => source === `schemas/tasknotes.task/${contractVersion}.schema.json`).document);
const contract = YAML.parse(pack.resources.find(({ source }) => source === `contracts/tasknotes.task/${contractVersion}.md`).document.split('\n---\n', 1)[0]);
for (const [role, schema] of Object.entries(fields)) {
  const formats = role === 'due' || role === 'scheduled' ? ['date', 'date-time', 'local-date-time'] : ['date-time', 'local-date-time'];
  const expected = JSON.stringify({ anyOf: formats.map((format) => ({ type: 'string', format })) });
  if ([schema, recordSchema.properties[role], contract.record_schema.value.properties[role]].some((value) => JSON.stringify(value) !== expected)) {
    throw new Error(`Unexpected TaskNotes schema for ${role}`);
  }
}
const output = '// Generated by scripts/verify-tasknotes-pack.mjs; do not edit.\n'
  + `export const TASKNOTES_TASK_CONTRACT_VERSION = '${contractVersion}';\n`
  + `export const TASKNOTES_MDBASE_TYPE_VERSION = ${seedType.version};\n`
  + 'export const taskDateSchemas = ' + JSON.stringify(fields, null, '\t') + ';\n'
  + 'export const canonicalTaskNotesResources = ' + JSON.stringify(pack.resources, null, '\t') + ';\n';
const destination = fileURLToPath(new URL('src/services/canonicalTaskNotesPack.ts', root));
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw new Error('Stale embedded TaskNotes pack');
} else writeFileSync(destination, output);
