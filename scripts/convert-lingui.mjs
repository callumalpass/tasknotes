// Re-runnable, lossless migration input reader. Never translates or executes remote code.
import { build } from "esbuild";
import { generateMessageId } from "@lingui/message-utils/generateMessageId";
import { formatter } from "@lingui/format-po";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import ts from "typescript";
import { readdir } from "node:fs/promises";
import { migratePlurals, pluralKeys } from "./lib/lingui-plurals.mjs";
import { legacyConceptReplacements } from "./lib/lingui-retired.mjs";

export const locales = ["en", "fr", "de", "es", "ja", "ko", "pt", "ru", "zh"];
export function flatten(tree, prefix = "") {
  return Object.fromEntries(Object.entries(tree).flatMap(([key, value]) => {
    const path = prefix ? `${prefix}.${key}` : key;
    return typeof value === "string" ? [[path, value]] : Object.entries(flatten(value, path));
  }));
}
// Legacy {parameter} syntax becomes ICU; template examples and apostrophes stay literal.
export function toICU(value) {
  return value.replaceAll("'", "''").replace(/\{\{[^{}]*\}\}|\{\w+\}|[{}]/g, token =>
    /^\{\w+\}$/.test(token) ? token : `'${token}'`);
}
export async function loadLegacy(root = process.cwd(), revisions = {}) {
  const result = {};
  for (const locale of locales) {
    const path = `src/i18n/resources/${locale}.ts`;
    const contents = revisions[locale]
      ? execFileSync("git", ["show", `${revisions[locale]}:${path}`], { cwd: root, encoding: "utf8" })
      : await readFile(resolve(root, path), "utf8");
    const built = await build({ stdin: { contents, loader: "ts", resolveDir: resolve(root, "src/i18n/resources") },
      bundle: true, format: "esm", platform: "node", write: false, logLevel: "silent" });
    const loaded = await import("data:text/javascript;base64," + Buffer.from(built.outputFiles[0].contents).toString("base64"));
    result[locale] = flatten(loaded[locale]);
  }
  return result;
}
export function mapping(english) {
  return Object.fromEntries(Object.entries(english).filter(([, value]) => value !== "").map(([key, value]) => {
    const replacement = legacyConceptReplacements[key];
    const message = replacement?.message ?? (pluralKeys.has(key) ? value : toICU(value));
    const context = replacement?.context ?? (/^ui\.taskCard\.reminderTooltip(One|Many)$/.test(key) ? "ui.taskCard.reminderTooltip" : key);
    return [key, { id: generateMessageId(message, context), message, context }];
  }));
}
// Existing PO values are already ICU. Never escape them a second time, or
// overwrite a translator's review merely because the importer is rerun.
export function importTranslation(locale, existing, reviewed, { replacement, plural = false, refreshReviewed = false } = {}) {
  if (replacement !== undefined) return locale === "en" ? replacement : existing ?? "";
  if (locale !== "en" && !refreshReviewed && existing) return existing;
  if (typeof reviewed !== "string" || !reviewed) throw new Error(`${locale}: missing reviewed migration input`);
  return plural ? reviewed : toICU(reviewed);
}
export async function convert({ root = process.cwd(), revisions = {}, inventory, refreshReviewed = false } = {}) {
  const resources = migratePlurals(await loadLegacy(root, revisions));
  const map = mapping(resources.en);
  const po = formatter({ origins: true, lineNumbers: false });
  for (const locale of locales) {
    const filename = resolve(root, `src/i18n/locales/${locale}/messages.po`);
    await mkdir(resolve(filename, ".."), { recursive: true });
    let existing = "";
    try { existing = await readFile(filename, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
    const entries = existing ? await po.parse(existing, { locale }) : {};
    for (const [key, { id, message, context }] of Object.entries(map)) {
      const translation = importTranslation(locale, entries[id]?.translation, resources[locale][key], {
        replacement: legacyConceptReplacements[key] ? message : undefined,
        plural: pluralKeys.has(key), refreshReviewed,
      });
      entries[id] = { ...entries[id], message, context, translation, obsolete: false,
        comments: [`Migrated concept: ${key}`], origin: [["src/i18n/messages.ts"]] };
    }
    await writeFile(filename, await po.serialize(entries, { locale, sourceLocale: "en", filename, existing }));
  }
  // Only the type-proven finite families need a runtime registry. Direct calls
  // already own macros; retaining every old key would keep dead catalogues alive.
  const finite = new Set(JSON.parse(await readFile(resolve(root, "scripts/plugin-finite-concepts.json"), "utf8")));
  for (const key of finite) if (!Object.hasOwn(map, key)) throw new Error(`Unknown finite migration concept: ${key}`);
  const registry = `// Generated by scripts/convert-lingui.mjs. PO files are the translation source.\nimport { msg } from "@lingui/core/macro";\nimport type { MessageDescriptor } from "@lingui/core";\n\nexport const messages = {\n` +
    Object.entries(map).filter(([key]) => finite.has(key)).map(([key, { message, context }]) => `${JSON.stringify(key)}: msg({ message: ${JSON.stringify(message)}, context: ${JSON.stringify(context)} }),`).join("\n") +
    `\n} satisfies Record<string, MessageDescriptor>;\nexport type MessageConcept = keyof typeof messages;\n\n/** Finite dynamic concept selection only; IDs are always generated by Lingui. */\nexport function messageForKey(key: MessageConcept): MessageDescriptor {\nconst descriptor = messages[key];\nif (!descriptor) throw new Error(\`Unknown message concept: \${key}\`);\nreturn descriptor;\n}\n`;
  await writeFile(resolve(root, "src/i18n/messages.ts"), registry);
  await writeFile(resolve(root, "scripts/plugin-key-map.json"), JSON.stringify(map, null, 2) + "\n");
  if (inventory) await writeFile(inventory, JSON.stringify(map, null, 2) + "\n");
  await syncMigratedDescriptors(root, map);
  console.log(`Converted ${Object.keys(map).length} concepts in ${locales.length} locales. Reviewer inputs: ${JSON.stringify(revisions)}`);
  return map;
}
// Update only migrated descriptors by their semantic context. New authored messages are untouched.
async function syncMigratedDescriptors(root, map) {
  const byContext = Object.fromEntries(Object.values(map).map(value => [value.context, value]));
  async function walk(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const path = resolve(dir, entry.name);
      if (entry.isDirectory()) { if (!["resources", "locales"].includes(entry.name)) await walk(path); continue; }
      if (!path.endsWith(".ts") || path.endsWith("/i18n/messages.ts")) continue;
      let text = await readFile(path, "utf8");
      const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
      const edits = [];
      function visit(node) {
        if (ts.isCallExpression(node) && node.expression.getText(source) === "msg" && ts.isObjectLiteralExpression(node.arguments[0])) {
          const object = node.arguments[0];
          const context = object.properties.find(prop => prop.name?.getText(source).replaceAll('"', '') === "context");
          const key = context && ts.isStringLiteral(context.initializer) ? context.initializer.text : undefined;
          const descriptor = Object.hasOwn(map, key) ? map[key] : Object.hasOwn(byContext, key) ? byContext[key] : undefined;
          if (descriptor) edits.push([object.getStart(source), object.end, `{ message: ${JSON.stringify(descriptor.message)}, context: ${JSON.stringify(descriptor.context)} }`]);
          return;
        }
        ts.forEachChild(node, visit);
      }
      visit(source);
      for (const [start, end, value] of edits.sort((a,b) => b[0]-a[0])) text = text.slice(0,start)+value+text.slice(end);
      if (edits.length) await writeFile(path, text);
    }
  }
  await walk(resolve(root, "src"));
}
if (process.argv[1]?.endsWith("convert-lingui.mjs")) {
  const revisions = Object.fromEntries(process.argv.slice(2).filter(x => x.includes("=")).map(x => x.split("=")));
  await convert({ revisions, inventory: process.env.PLUGIN_KEY_INVENTORY, refreshReviewed: process.argv.includes("--refresh-reviewed") });
}
